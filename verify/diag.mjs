import http from "node:http";
import path from "node:path";
import { spawn } from "node:child_process";
import { fileURLToPath } from "node:url";
const here = path.dirname(fileURLToPath(import.meta.url));
const agentDir = path.join(here, "agent");
const extensionPath = path.resolve(here, "..", "index.ts");
const cliJs = "C:/Users/Administrator/.pi/agent/install/releases/1.4.0/node_modules/@earendil-works/pi-coding-agent/dist/bundle/cli.js";
let n = 0;
const server = http.createServer((req, res) => {
  let body = "";
  req.on("data", (c) => { body += c; });
  req.on("end", () => {
    n++;
    console.log("[req] " + req.method + " " + req.url + " bytes=" + body.length);
    console.log("[req] body head: " + body.slice(0, 300).replace(/\s+/g, " "));
    res.writeHead(200, { "content-type": "text/event-stream", "cache-control": "no-cache" });
    const c = JSON.stringify({ id: "x", object: "chat.completion.chunk", created: 1, model: "stub-1", choices: [{ index: 0, delta: { role: "assistant", content: "hello" }, finish_reason: null }] });
    res.write("data: " + c + "\n\n");
    const d = JSON.stringify({ id: "x", object: "chat.completion.chunk", created: 1, model: "stub-1", choices: [{ index: 0, delta: {}, finish_reason: "stop" }], usage: { prompt_tokens: 1, completion_tokens: 1, total_tokens: 2 } });
    res.write("data: " + d + "\n\n");
    res.write("data: [DONE]\n\n");
    res.end();
  });
});
await new Promise((r) => server.listen(18765, "127.0.0.1", r));
console.log("[srv] up");
const args = [cliJs, "-p", "say hi", "--model", "stub/stub-1", "--api-key", "stub-key", "--no-tools", "--no-session", "--no-skills", "--no-mcp", "--no-context-files", "--no-prompt-templates", "--no-themes", "--no-extensions", "-e", extensionPath];
const env = Object.assign({}, process.env, { PI_CODING_AGENT_DIR: agentDir });
const child = spawn(process.execPath, args, { env: env, cwd: path.resolve(here, "..") });
let out = ""; let err = "";
child.stdout.on("data", (d) => { out += d; process.stdout.write("[out] " + d); });
child.stderr.on("data", (d) => { err += d; process.stdout.write("[err] " + d); });
const timer = setTimeout(() => { console.log("[diag] 25s 未退出，强杀子进程"); child.kill(); }, 25000);
const code = await new Promise((r) => child.on("close", (c) => r(c)));
clearTimeout(timer);
console.log("[diag] exit=" + code + " requests=" + n);
console.log("[diag] stdout len=" + out.length + " stderr len=" + err.length);
console.log("[diag] stderr tail: " + err.slice(-800));
server.close();
process.exit(0);
